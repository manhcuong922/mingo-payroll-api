using MPS.Domain.Enums.Payroll;

namespace MPS.Domain.Entities.Payroll;

/// <summary>
/// Ghi chú trên bảng lương: trần/ngưỡng tĩnh, giới hạn phụ cấp, hoặc thay đổi luật so kỳ trước
/// (từ <see cref="OldValue"/> → <see cref="NewValue"/> theo <see cref="LegalReference"/>).
/// </summary>
public class PayrollNote
{
    public int Id { get; set; }

    public int PayrollPeriodId { get; set; }
    public PayrollPeriod PayrollPeriod { get; set; } = null!;

    public PayrollNoteType NoteType { get; set; }

    /// <summary>Cột được chú thích (null = ghi chú cấp bảng).</summary>
    public string? ColumnCode { get; set; }

    public string Title { get; set; } = string.Empty;
    public string Body { get; set; } = string.Empty;

    // ===== LawChange =====
    public decimal? OldValue { get; set; }
    public decimal? NewValue { get; set; }
    public string? LegalReference { get; set; }
    public ComplianceVersionType? VersionType { get; set; }

    public bool AutoGenerated { get; set; }

    public DateTime CreatedAt { get; set; }
    public int? CreatedByUserId { get; set; }
    public User? CreatedByUser { get; set; }
}
