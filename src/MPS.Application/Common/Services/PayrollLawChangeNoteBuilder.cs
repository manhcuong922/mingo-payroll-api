using MPS.Application.Common.Interfaces.Payroll;
using MPS.Application.Common.Payroll.Formula;
using MPS.Domain.Entities.Payroll;
using MPS.Domain.Enums.Payroll;

namespace MPS.Application.Common.Services;

/// <inheritdoc />
public sealed class PayrollLawChangeNoteBuilder : IPayrollLawChangeNoteBuilder
{
    public IReadOnlyList<PayrollNote> Build(
        IReadOnlyList<PayrollComplianceRef> currentRefs,
        IReadOnlyList<PayrollComplianceRef>? previousRefs)
    {
        var notes = new List<PayrollNote>();
        var now = DateTime.UtcNow;

        foreach (var cur in currentRefs)
        {
            // (1) Ghi chú trần/ngưỡng tĩnh của kỳ.
            if (cur.HeadlineValue is { } value && cur.HeadlineLabel is { Length: > 0 } label)
            {
                notes.Add(new PayrollNote
                {
                    NoteType = PayrollNoteType.CapThreshold,
                    Title = label,
                    Body = $"{label}: {PayrollNumberFormat.Format(value)} — {cur.LegalReference}",
                    VersionType = cur.VersionType,
                    NewValue = value,
                    LegalReference = cur.LegalReference,
                    AutoGenerated = true,
                    CreatedAt = now,
                });
            }

            // (2) Ghi chú thay đổi luật so kỳ trước (cùng loại + scope).
            var prev = previousRefs?.FirstOrDefault(p => p.VersionType == cur.VersionType && p.ScopeId == cur.ScopeId);
            if (prev is null || prev.VersionId == cur.VersionId) continue;

            var changedValue = cur.HeadlineValue.HasValue && prev.HeadlineValue.HasValue && cur.HeadlineValue != prev.HeadlineValue;
            var body = changedValue
                ? $"{cur.HeadlineLabel}: {PayrollNumberFormat.Format(prev.HeadlineValue!.Value)} → {PayrollNumberFormat.Format(cur.HeadlineValue!.Value)} theo {cur.LegalReference}."
                : $"Áp dụng version mới: {cur.LegalReference} (trước đó: {prev.LegalReference}).";

            notes.Add(new PayrollNote
            {
                NoteType = PayrollNoteType.LawChange,
                Title = $"Thay đổi luật: {VersionTypeLabel(cur.VersionType)}",
                Body = body,
                VersionType = cur.VersionType,
                OldValue = prev.HeadlineValue,
                NewValue = cur.HeadlineValue,
                LegalReference = cur.LegalReference,
                AutoGenerated = true,
                CreatedAt = now,
            });
        }

        return notes;
    }

    private static string VersionTypeLabel(ComplianceVersionType type) => type switch
    {
        ComplianceVersionType.SocialInsurance => "Bảo hiểm xã hội",
        ComplianceVersionType.Pit => "Thuế TNCN",
        ComplianceVersionType.MinimumWage => "Lương tối thiểu vùng",
        ComplianceVersionType.LaborLawConstants => "Hằng số luật lao động",
        ComplianceVersionType.AllowanceThreshold => "Ngưỡng miễn thuế phụ cấp",
        _ => type.ToString(),
    };
}
