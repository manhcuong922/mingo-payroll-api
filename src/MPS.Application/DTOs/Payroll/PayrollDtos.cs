namespace MPS.Application.DTOs.Payroll;

public sealed record PayrollCellDto(
    string ColumnCode,
    decimal? Value,
    string? Text,
    bool IsOverridden,
    string? Explanation);

public sealed record PayrollRowDto(
    int RowId,
    string RowType,
    int? EmployeeInformationId,
    string? EmployeeName,
    IReadOnlyList<PayrollCellDto> Cells);

public sealed record PayrollColumnDto(
    string ColumnCode,
    string Label,
    string? GroupName,
    int DisplayOrder,
    string DataType,
    string ValueSource,
    bool IsMoney,
    bool IsEditable);

public sealed record PayrollNoteDto(
    int Id,
    string NoteType,
    string? ColumnCode,
    string Title,
    string Body,
    decimal? OldValue,
    decimal? NewValue,
    string? LegalReference,
    bool AutoGenerated);

public sealed record PayrollComplianceRefDto(
    string VersionType,
    int VersionId,
    DateOnly ValidFrom,
    string LegalReference,
    string? HeadlineLabel,
    decimal? HeadlineValue);

public sealed record PayrollSheetDto(
    int Id,
    int PeriodYear,
    int PeriodMonth,
    DateOnly PayDate,
    decimal StandardWorkingDays,
    string Status,
    bool IsStale,
    string? StaleReason,
    DateTime? StaleMarkedAt,
    IReadOnlyList<PayrollColumnDto> Columns,
    IReadOnlyList<PayrollRowDto> Rows,
    IReadOnlyList<PayrollNoteDto> Notes,
    IReadOnlyList<PayrollComplianceRefDto> ComplianceRefs);

public sealed record PayrollPeriodSummaryDto(
    int Id,
    int PeriodYear,
    int PeriodMonth,
    string Status,
    DateOnly PayDate,
    int EmployeeCount);

/// <summary>Phiếu lương rút gọn của chính NV (1 kỳ đã chốt): gross = TONGTHUNHAP, net = THUCNHAN.</summary>
public sealed record MyPayslipDto(
    int PeriodId,
    int Year,
    int Month,
    DateOnly PayDate,
    string Status,
    decimal? Gross,
    decimal? Net);

/// <summary>Header phiếu lương cá nhân — thông tin NV để render tiêu đề phiếu.</summary>
public sealed record EmployeePayslipHeaderDto(
    int EmployeeInformationId,
    string FullName,
    string? PositionName,
    string? BankAccountLast4);

/// <summary>
/// Phiếu lương chi tiết của chính NV trong 1 kỳ đã chốt. <c>Sheet</c> khớp 1-1 với
/// <see cref="PayrollSheetDto"/> (FE tái dùng &lt;PayrollSheetTable&gt;) nhưng <c>Rows</c> chỉ có ĐÚNG 1
/// phần tử — dòng của chính NV, không có dòng Total. <c>Gross</c>/<c>Net</c> tiện cho dashboard/biểu đồ.
/// </summary>
public sealed record MyPayslipDetailDto(
    PayrollSheetDto Sheet,
    EmployeePayslipHeaderDto Employee,
    decimal? Gross,
    decimal? Net);

public sealed record PayrollReadinessDto(
    int EmployeeInformationId,
    string EmployeeCode,
    string FullName,
    bool IsReady,
    IReadOnlyList<string> Missing,
    IReadOnlyList<string> Warnings);
