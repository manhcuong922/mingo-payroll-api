using MediatR;
using MPS.Application.DTOs.Payroll;
using MPS.Application.Features.Payroll.Common;
using MPS.Domain.Entities.Payroll;
using MPS.Domain.Enums.Payroll;
using MPS.Domain.Exceptions;
using MPS.Domain.Interfaces.Payroll;

namespace MPS.Application.Features.Payroll.Queries;

public sealed record GetPayrollSheetQuery(int PeriodId) : IRequest<PayrollSheetDto>;

public sealed class GetPayrollSheetQueryHandler : IRequestHandler<GetPayrollSheetQuery, PayrollSheetDto>
{
    private readonly IPayrollPeriodRepository _periods;
    public GetPayrollSheetQueryHandler(IPayrollPeriodRepository periods) => _periods = periods;

    public async Task<PayrollSheetDto> Handle(GetPayrollSheetQuery request, CancellationToken ct)
    {
        var period = await _periods.GetFullAsync(request.PeriodId, asNoTracking: true, ct)
            ?? throw new NotFoundException($"Không tìm thấy kỳ lương #{request.PeriodId}.");
        return PayrollSheetMapper.Map(period);
    }
}

public static class PayrollSheetMapper
{
    public static PayrollSheetDto Map(PayrollPeriod period)
    {
        var columns = PayrollColumnSnapshotMapper.Deserialize(period.FormulaSnapshotJson)
            .OrderBy(c => c.DisplayOrder)
            .Select(c => new PayrollColumnDto(
                c.ColumnCode, c.Label, c.GroupName, c.DisplayOrder,
                c.DataType.ToString(), c.ValueSource.ToString(), c.IsMoney, c.IsEditable))
            .ToList();

        var rows = period.Rows
            .OrderBy(r => r.RowType == PayrollRowType.Total)
            .ThenBy(r => r.DisplayOrder)
            .Select(r => new PayrollRowDto(
                r.Id,
                r.RowType.ToString(),
                r.EmployeeInformationId,
                r.EmployeeInformation?.FullName,
                r.Cells.Select(c => new PayrollCellDto(
                    c.ColumnCode,
                    c.IsOverridden ? c.OverrideValue : c.ComputedValue,
                    c.TextValue,
                    c.IsOverridden,
                    c.ExplanationJson)).ToList()))
            .ToList();

        var notes = period.Notes
            .Select(n => new PayrollNoteDto(
                n.Id, n.NoteType.ToString(), n.ColumnCode, n.Title, n.Body,
                n.OldValue, n.NewValue, n.LegalReference, n.AutoGenerated))
            .ToList();

        var refs = period.ComplianceRefs
            .Select(r => new PayrollComplianceRefDto(
                r.VersionType.ToString(), r.VersionId, r.ValidFrom, r.LegalReference,
                r.HeadlineLabel, r.HeadlineValue))
            .ToList();

        return new PayrollSheetDto(
            period.Id, period.PeriodYear, period.PeriodMonth,
            period.PayDate, period.StandardWorkingDays, period.Status.ToString(),
            columns, rows, notes, refs);
    }
}
