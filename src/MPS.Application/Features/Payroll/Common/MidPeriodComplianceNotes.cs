using MPS.Application.Common.Models.Compliance;
using MPS.Domain.Entities.Payroll;
using MPS.Domain.Enums.Payroll;

namespace MPS.Application.Features.Payroll.Common;

/// <summary>
/// ⭐ [Mục 1] Ghi chú cho trường hợp luật đổi NGAY TRONG KỲ.
///
/// <para><c>PayrollLawChangeNoteBuilder</c> chỉ so version của kỳ này với KỲ TRƯỚC, nên khi luật đổi
/// giữa tháng nó vẫn sinh đúng một dòng "kỳ 6 khác kỳ 5" mà không nói gì về việc bên trong kỳ 6 có
/// hai mức. Kế toán nhìn bảng lương không có cách nào biết vì sao hai người cùng số giờ tăng ca lại
/// ra hai số tiền khác nhau. Ghi chú này trả lời đúng câu đó.</para>
///
/// <para>Thuần (không I/O) để test độc lập.</para>
/// </summary>
public static class MidPeriodComplianceNotes
{
    /// <summary>
    /// Ghi chú "hằng số luật lao động đổi giữa kỳ" — null khi cả kỳ chỉ dùng một version (đường phổ biến).
    /// </summary>
    public static PayrollNote? ForLaborLaw(LaborLawTimeline timeline, DateTime nowUtc)
    {
        if (!timeline.ChangedWithinPeriod) return null;

        var moments = string.Join(", ", timeline.Versions.Select(v => $"{v.ValidFrom:dd/MM/yyyy} ({v.LegalReference})"));
        var latest = timeline.Versions[^1];

        return new PayrollNote
        {
            NoteType = PayrollNoteType.LawChange,
            VersionType = ComplianceVersionType.LaborLawConstants,
            Title = "Hằng số luật lao động đổi giữa kỳ",
            Body = $"Trong kỳ có {timeline.Versions.Count} mức hiệu lực: {moments}. "
                + "Tăng ca, phụ trội ngày nghỉ/lễ, phụ cấp làm đêm và khung giờ đêm được tính theo luật "
                + "của TỪNG NGÀY CÔNG — ngày trước mốc hiệu lực giữ mức cũ, từ mốc trở đi áp mức mới. "
                + "Đơn giá giờ và công chuẩn tháng vẫn là một con số chung cho cả kỳ.",
            LegalReference = latest.LegalReference,
            AutoGenerated = true,
            CreatedAt = nowUtc,
        };
    }

    /// <summary>
    /// ⭐ [Mục 2] Ghi chú "tỷ lệ bảo hiểm là số BÌNH QUÂN theo ngày" — null khi cả kỳ chỉ một mức.
    ///
    /// <para>Bắt buộc phải có: con số trên cột bảo hiểm lúc đó KHÔNG khớp với bất kỳ văn bản nào kế
    /// toán tra được, nên nếu không nói rõ thì người đối chiếu sẽ tưởng hệ thống tính sai. Ghi chú
    /// cũng nêu thẳng sai số đã biết ở nhóm chạm trần để không ai phát hiện muộn.</para>
    /// </summary>
    public static PayrollNote? ForInsurance(InsurancePeriodRates rates, int periodDays, DateTime nowUtc)
    {
        if (!rates.ChangedWithinPeriod) return null;

        var moments = rates.SocialVersions
            .Select(v => $"BHXH {v.ValidFrom:dd/MM/yyyy} ({v.LegalReference})")
            .Concat(rates.MinWageVersions.Count > 1
                ? rates.MinWageVersions.Select(v => $"LTT vùng {v.ValidFrom:dd/MM/yyyy} ({v.LegalReference})")
                : Array.Empty<string>());

        return new PayrollNote
        {
            NoteType = PayrollNoteType.LawChange,
            VersionType = ComplianceVersionType.SocialInsurance,
            Title = "Tỷ lệ bảo hiểm là số bình quân theo ngày",
            Body = $"Văn bản bảo hiểm đổi giữa kỳ: {string.Join("; ", moments)}. "
                + $"Tỷ lệ và trần trên khối Bảo hiểm là BÌNH QUÂN theo {periodDays} ngày lịch của kỳ "
                + "(số ngày trước mốc giữ mức cũ, số ngày từ mốc giữ mức mới), nên KHÔNG khớp với "
                + "con số ghi trong bất kỳ văn bản đơn lẻ nào — đây là kết quả đúng của việc chia theo ngày. "
                + "Lưu ý: cách bình quân chính xác tuyệt đối với người có nền đóng DƯỚI trần; "
                + "người đã CHẠM TRẦN có thể lệch nhỏ so với tách đôi kỳ.",
            LegalReference = rates.SocialVersions[^1].LegalReference,
            AutoGenerated = true,
            CreatedAt = nowUtc,
        };
    }
}
