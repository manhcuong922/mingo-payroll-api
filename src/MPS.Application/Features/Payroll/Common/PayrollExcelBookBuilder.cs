/// <summary>
/// Dựng <see cref="PayrollExcelBook"/> từ SNAPSHOT của kỳ (không đọc lại module) — mọi số trong file
/// đúng bằng số hệ thống đã chốt. Quyết định bố cục: field nào thành hằng số hàng 9/10, field nào
/// thành cột phụ trợ, rồi dịch từng công thức sang Excel theo đúng dòng.
/// </summary>
public sealed class PayrollExcelBookBuilder
{
    private readonly IPayrollFieldCatalog _catalog;

    public PayrollExcelBookBuilder(IPayrollFieldCatalog catalog) => _catalog = catalog;

    private sealed record ParamSnap(string Key, string Name, decimal Value);

    public PayrollExcelBook Build(PayrollPeriod period, string companyName)
    {
        var columns = PayrollColumnSnapshotMapper.Deserialize(period.FormulaSnapshotJson)
            .OrderBy(c => c.DisplayOrder).ToList();

        var employeeRows = period.Rows.Where(r => r.RowType == PayrollRowType.Employee)
            .OrderBy(r => r.DisplayOrder).ToList();
        var totalRow = period.Rows.FirstOrDefault(r => r.RowType == PayrollRowType.Total);

        var asts = BuildAsts(columns);
        var inputs = employeeRows.ToDictionary(
            r => r.Id, r => PayrollEmployeeInputs.FromSnapshotJson(r.EmployeeInformationId ?? 0, r.InputSnapshotJson));

        var paramSnaps = (PayrollJson.Deserialize<List<ParamSnap>>(period.ParamsSnapshotJson) ?? new())
            .ToDictionary(p => p.Key, StringComparer.Ordinal);
        var brackets = PayrollJson.Deserialize<List<PitBracketSnapshot>>(period.PitBracketsSnapshotJson) ?? new();

        var (fieldRefs, paramRefs) = CollectReferences(columns, asts);

        // Field là hằng số của kỳ → hàng 9/10; còn lại (hệ số năng suất, số công…) → cột phụ trợ.
        var constantFields = fieldRefs.Keys
            .Where(k => PayrollExcelConstantCatalog.TryGetField(k, out _) && IsUniform(k, inputs.Values))
            .ToHashSet(StringComparer.Ordinal);
        var helperFields = fieldRefs.Keys.Where(k => !constantFields.Contains(k)).ToList();

        var laidOut = LayOutColumns(columns, fieldRefs, helperFields);
        var constants = PlaceConstants(laidOut, constantFields, fieldRefs, paramRefs, paramSnaps, inputs.Values);

        var refsByRow = new Dictionary<int, PayrollExcelRefs>();
        PayrollExcelRefs RefsFor(int excelRow)
        {
            if (refsByRow.TryGetValue(excelRow, out var cached)) return cached;
            var built = BuildRefs(laidOut, constants, excelRow, brackets);
            refsByRow[excelRow] = built;
            return built;
        }

        var dataRows = new List<PayrollExcelDataRow>();
        for (var i = 0; i < employeeRows.Count; i++)
        {
            var excelRow = PayrollExcelLayout.RowFirstData + i;
            dataRows.Add(BuildDataRow(employeeRows[i], i + 1, laidOut, asts, inputs, RefsFor(excelRow)));
        }

        var lastRow = PayrollExcelLayout.RowFirstData + Math.Max(employeeRows.Count, 1) - 1;
        var totals = BuildTotalRow(laidOut, totalRow, lastRow);
        var notes = MapNotes(period);

        return new PayrollExcelBook(
            companyName, period.PeriodYear, period.PeriodMonth, period.Status.ToString(),
            period.StandardWorkingDays, laidOut, dataRows, totals, constants, brackets,
            notes, MapComplianceRefs(period));
    }

    private static List<PayrollNoteDto> MapNotes(PayrollPeriod period) => period.Notes
        .OrderBy(n => n.NoteType).ThenBy(n => n.Id)
        .Select(n => new PayrollNoteDto(
            n.Id, n.NoteType.ToString(), n.ColumnCode, n.Title, n.Body,
            n.OldValue, n.NewValue, n.LegalReference, n.AutoGenerated))
        .ToList();

    private static List<PayrollComplianceRefDto> MapComplianceRefs(PayrollPeriod period) => period.ComplianceRefs
        .Select(r => new PayrollComplianceRefDto(
            r.VersionType.ToString(), r.VersionId, r.ValidFrom, r.LegalReference,
            r.HeadlineLabel, r.HeadlineValue))
        .ToList();

    // ===================== Bố cục =====================

    private static Dictionary<string, FormulaNode> BuildAsts(IEnumerable<SalaryColumnDefinition> columns)
    {
        var map = new Dictionary<string, FormulaNode>(StringComparer.Ordinal);
        foreach (var c in columns)
        {
            if (c.ValueSource != ColumnValueSource.Formula || string.IsNullOrEmpty(c.FormulaJson)) continue;
            var ast = PayrollJson.Deserialize<FormulaNode>(c.FormulaJson);
            if (ast is not null) map[c.ColumnCode] = ast;
        }
        return map;
    }

    /// <summary>Khoá field/param → chỉ số cột ĐẦU TIÊN tham chiếu nó (dùng làm cột neo cho hằng số).</summary>
    private static (Dictionary<string, int> Fields, Dictionary<string, int> Params) CollectReferences(
        IReadOnlyList<SalaryColumnDefinition> columns, IReadOnlyDictionary<string, FormulaNode> asts)
    {
        var fields = new Dictionary<string, int>(StringComparer.Ordinal);
        var @params = new Dictionary<string, int>(StringComparer.Ordinal);

        for (var i = 0; i < columns.Count; i++)
        {
            if (!asts.TryGetValue(columns[i].ColumnCode, out var ast)) continue;
            foreach (var (key, isParam) in Walk(ast))
            {
                var target = isParam ? @params : fields;
                if (!target.ContainsKey(key)) target[key] = i;
            }
        }
        return (fields, @params);
    }

    private static IEnumerable<(string Key, bool IsParam)> Walk(FormulaNode node)
    {
        if (node.Type == FormulaNodeType.Field && node.Text is { Length: > 0 }) yield return (node.Text, false);
        if (node.Type == FormulaNodeType.Param && node.Text is { Length: > 0 }) yield return (node.Text, true);
        foreach (var child in node.Args)
            foreach (var found in Walk(child))
                yield return found;
    }

    private static bool IsUniform(string key, IEnumerable<PayrollEmployeeInputs> inputs)
    {
        decimal? first = null;
        foreach (var i in inputs)
        {
            var v = i.Numbers.GetValueOrDefault(key, 0m);
            if (first is null) { first = v; continue; }
            if (first.Value != v) return false;
        }
        return true;
    }

    private List<PayrollExcelColumn> LayOutColumns(
        IReadOnlyList<SalaryColumnDefinition> columns,
        IReadOnlyDictionary<string, int> fieldRefs,
        IReadOnlyList<string> helperFields)
    {
        var helpersByAnchor = helperFields
            .GroupBy(f => fieldRefs[f])
            .ToDictionary(g => g.Key, g => g.OrderBy(x => x, StringComparer.Ordinal).ToList());

        var result = new List<PayrollExcelColumn>
        {
            new("STT", "STT", null, PayrollExcelLayout.ColumnLetter(1), 1,
                ColumnDataType.Number, ColumnValueSource.Formula, RoundingMode.None, false),
        };
        var index = PayrollExcelLayout.FirstDataColumnIndex;

        void AddHelpers(int anchor, string? group)
        {
            if (!helpersByAnchor.TryGetValue(anchor, out var keys)) return;
            foreach (var key in keys)
            {
                var type = _catalog.TryGet(key, out var d) ? d.DataType : ColumnDataType.Number;
                result.Add(new PayrollExcelColumn(
                    key, _catalog.LabelOf(key), group, PayrollExcelLayout.ColumnLetter(index), index,
                    type, ColumnValueSource.Lookup, RoundingMode.None, type == ColumnDataType.Money, key));
                index++;
            }
        }

        for (var i = 0; i < columns.Count; i++)
        {
            var c = columns[i];
            AddHelpers(i, c.GroupName);
            result.Add(new PayrollExcelColumn(
                c.ColumnCode, c.Label, c.GroupName, PayrollExcelLayout.ColumnLetter(index), index,
                c.DataType, c.ValueSource, c.Rounding, c.IsMoney));
            index++;
        }
        return result;
    }

    /// <summary>
    /// Đặt hằng số vào hàng 9 (tỷ lệ/đơn giá) hoặc 10 (trần/giảm trừ) dưới cột đầu tiên dùng nó, như
    /// file mẫu. Nếu ô đó đã có hằng số khác chiếm chỗ → chuyển sang sheet THAM SO (không ghi đè).
    /// </summary>
    private List<PayrollExcelConstant> PlaceConstants(
        IReadOnlyList<PayrollExcelColumn> laidOut,
        IReadOnlySet<string> constantFields,
        IReadOnlyDictionary<string, int> fieldRefs,
        IReadOnlyDictionary<string, int> paramRefs,
        IReadOnlyDictionary<string, ParamSnap> paramSnaps,
        IEnumerable<PayrollEmployeeInputs> inputs)
    {
        var firstInputs = inputs.FirstOrDefault();
        var byOriginalOrder = laidOut.Where(c => c.FieldKey is null && c.ColumnCode != "STT").ToList();
        var taken = new HashSet<string>(StringComparer.Ordinal);
        var result = new List<PayrollExcelConstant>();

        PayrollExcelConstant Place(string key, ConstantPlacement placement, string label, decimal value, int anchorIndex)
        {
            var row = placement.IsRateRow ? PayrollExcelLayout.RowRateParam : PayrollExcelLayout.RowCapParam;

            if (anchorIndex >= 0 && anchorIndex < byOriginalOrder.Count)
            {
                var cellRef = $"{byOriginalOrder[anchorIndex].Letter}{row}";
                if (taken.Add(cellRef))
                    return new PayrollExcelConstant(
                        key, placement.Name, label, value, placement.IsPercent, PayrollExcelLayout.SheetSalary, cellRef);
            }
            // Không có cột neo (hoặc ô đã bị hằng số khác chiếm) → giá trị nằm ở chính dòng liệt kê
            // của nó trên sheet THAM SO, nên named range luôn trỏ đúng ô có số.
            return new PayrollExcelConstant(
                key, placement.Name, label, value, placement.IsPercent, PayrollExcelLayout.SheetParams,
                $"C{PayrollExcelLayout.RowFirstConstant + result.Count}");
        }

        foreach (var key in constantFields.OrderBy(k => fieldRefs[k]))
        {
            PayrollExcelConstantCatalog.TryGetField(key, out var placement);
            var value = firstInputs?.Numbers.GetValueOrDefault(key, 0m) ?? 0m;
            result.Add(Place(key, placement, _catalog.LabelOf(key), value, fieldRefs[key]));
        }

        foreach (var key in paramRefs.Keys.OrderBy(k => paramRefs[k]))
        {
            var snap = paramSnaps.GetValueOrDefault(key);
            result.Add(Place(key, PayrollExcelConstantCatalog.GetParam(key),
                snap?.Name ?? key, snap?.Value ?? 0m, paramRefs[key]));
        }

        return result;
    }

    private PayrollExcelRefs BuildRefs(
        IReadOnlyList<PayrollExcelColumn> laidOut,
        IReadOnlyList<PayrollExcelConstant> constants,
        int excelRow,
        IReadOnlyList<PitBracketSnapshot> brackets)
    {
        var columnRefs = new Dictionary<string, string>(StringComparer.Ordinal);
        var fieldRefs = new Dictionary<string, string>(StringComparer.Ordinal);
        var textColumns = new HashSet<string>(StringComparer.Ordinal);

        foreach (var c in laidOut)
        {
            if (c.FieldKey is null)
            {
                columnRefs[c.ColumnCode] = $"{c.Letter}{excelRow}";
                if (c.DataType == ColumnDataType.Text) textColumns.Add(c.ColumnCode);
            }
            else
            {
                fieldRefs[c.FieldKey] = $"{c.Letter}{excelRow}";
            }
        }

        var paramRefs = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var k in constants)
        {
            if (PayrollExcelConstantCatalog.TryGetField(k.Key, out _)) fieldRefs[k.Key] = k.Name;
            else paramRefs[k.Key] = k.Name;
        }

        var textFields = _catalog.GetAll().Where(f => f.IsText).Select(f => f.Key).ToHashSet(StringComparer.Ordinal);
        return new PayrollExcelRefs(columnRefs, fieldRefs, paramRefs, textColumns, textFields, brackets);
    }

    // ===================== Dữ liệu =====================

    private static PayrollExcelDataRow BuildDataRow(
        PayrollRow row, int ordinal,
        IReadOnlyList<PayrollExcelColumn> laidOut,
        IReadOnlyDictionary<string, FormulaNode> asts,
        IReadOnlyDictionary<int, PayrollEmployeeInputs> inputs,
        PayrollExcelRefs refs)
    {
        var cellsByCode = row.Cells.ToDictionary(c => c.ColumnCode, StringComparer.Ordinal);
        var rowInputs = inputs[row.Id];
        var cells = new List<PayrollExcelCell>(laidOut.Count);

        foreach (var col in laidOut)
        {
            if (col.ColumnCode == "STT" && col.FieldKey is null)
            {
                cells.Add(new PayrollExcelCell(Number: ordinal, Formula: "ROW()-12"));
                continue;
            }

            if (col.FieldKey is { } fieldKey)
            {
                cells.Add(col.DataType == ColumnDataType.Text
                    ? new PayrollExcelCell(Text: rowInputs.Texts.GetValueOrDefault(fieldKey, string.Empty))
                    : new PayrollExcelCell(Number: rowInputs.Numbers.GetValueOrDefault(fieldKey, 0m)));
                continue;
            }

            cells.Add(BuildCell(col, cellsByCode.GetValueOrDefault(col.ColumnCode), asts, refs));
        }

        return new PayrollExcelDataRow(ordinal, cells);
    }

    private static PayrollExcelCell BuildCell(
        PayrollExcelColumn col, PayrollCellValue? cell,
        IReadOnlyDictionary<string, FormulaNode> asts, PayrollExcelRefs refs)
    {
        if (cell is null) return new PayrollExcelCell();

        if (col.DataType == ColumnDataType.Text) return new PayrollExcelCell(Text: cell.TextValue ?? string.Empty);

        // Ô sửa tay: ghi số cứng (mất công thức) — các cột phụ thuộc vẫn trỏ vào ô này nên Excel tính lại đúng.
        if (cell.IsOverridden)
        {
            var computed = cell.ComputedValue.HasValue
                ? $" Giá trị hệ thống tính: {PayrollNumberFormat.Format(cell.ComputedValue.Value)}."
                : string.Empty;
            return new PayrollExcelCell(
                Number: cell.OverrideValue, IsOverridden: true,
                Comment: $"Ô đã sửa tay nên không còn công thức.{computed}");
        }

        if (col.ValueSource == ColumnValueSource.Formula && asts.TryGetValue(col.ColumnCode, out var ast))
        {
            var formula = PayrollExcelFormulaTranslator.Wrap(
                PayrollExcelFormulaTranslator.Translate(ast, refs), col.Rounding, col.DataType);
            return new PayrollExcelCell(Number: cell.ComputedValue, Formula: formula);
        }

        return new PayrollExcelCell(Number: cell.ComputedValue);
    }

    private static List<PayrollExcelCell> BuildTotalRow(
        IReadOnlyList<PayrollExcelColumn> laidOut, PayrollRow? totalRow, int lastRow)
    {
        var cellsByCode = totalRow?.Cells.ToDictionary(c => c.ColumnCode, StringComparer.Ordinal)
            ?? new Dictionary<string, PayrollCellValue>(StringComparer.Ordinal);

        return laidOut.Select(col =>
        {
            if (col.Index == PayrollExcelLayout.FirstDataColumnIndex)
                return new PayrollExcelCell(Text: PayrollExcelLayout.TotalRowLabel);
            if (!col.IsMoney) return new PayrollExcelCell();

            var stored = cellsByCode.GetValueOrDefault(col.ColumnCode);
            var value = stored is null ? null : stored.IsOverridden ? stored.OverrideValue : stored.ComputedValue;
            return new PayrollExcelCell(
                Number: value,
                Formula: $"SUM({col.Letter}{PayrollExcelLayout.RowFirstData}:{col.Letter}{lastRow})");
        }).ToList();
    }

}
