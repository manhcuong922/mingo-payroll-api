using FluentAssertions;
using MPS.Application.Common.Models.Compliance;
using MPS.Application.Features.Payroll.Common;
using MPS.Domain.Enums.Payroll;

namespace MPS.Application.Tests.Features.Payroll;

/// <summary>
/// [Mục 1] Bảng tra hằng số luật lao động theo ngày + ghi chú "luật đổi giữa kỳ".
/// </summary>
public sealed class LaborLawTimelineTests
{
    private static LaborLawConstantsSnapshot Law(int versionId, DateOnly validFrom, string legalRef) => new(
        VersionId: versionId, ValidFrom: validFrom,
        ProbationSalaryMinPercent: 85m,
        OvertimeNightExtraPercent: 20m, NightWorkSurchargePercent: 30m, OvertimeNormalUpliftPercent: 50m,
        NightStartTime: new TimeOnly(22, 0), NightEndTime: new TimeOnly(6, 0),
        StandardWorkingHoursPerDay: 8m, MaxRegularHoursPerWeek: 48m, StandardWorkingDaysPerMonth: 26m,
        AnnualLeaveMinDays: 12,
        WorkRateNormalFloor: 100m, WorkRateWeeklyRestFloor: 200m, WorkRateHolidayFloor: 300m,
        OvertimeMaxHoursPerDay: 4m, OvertimeMaxHoursPerMonth: 40m, OvertimeMaxHoursPerYear: 300,
        LegalReference: legalRef);

    private static readonly LaborLawConstantsSnapshot OldLaw =
        Law(1, new DateOnly(2021, 1, 1), "BLLĐ 2019 Đ.98");
    private static readonly LaborLawConstantsSnapshot NewLaw =
        Law(2, new DateOnly(2026, 6, 15), "NĐ 99/2026 Đ.5");

    /// <summary>Kỳ 06/2026 có mốc đổi luật ngày 15/06, phủ cả 01/07 cho OT vắt nửa đêm cuối tháng.</summary>
    private static LaborLawTimeline SplitJune()
    {
        var byDate = new Dictionary<DateOnly, LaborLawConstantsSnapshot>();
        for (var d = new DateOnly(2026, 6, 1); d <= new DateOnly(2026, 7, 1); d = d.AddDays(1))
            byDate[d] = d >= new DateOnly(2026, 6, 15) ? NewLaw : OldLaw;
        return new LaborLawTimeline(byDate, NewLaw);
    }

    [Fact]
    public void For_NgayTruocMoc_TraLuatCu()
    {
        SplitJune().For(new DateOnly(2026, 6, 14)).VersionId.Should().Be(1);
    }

    [Fact]
    public void For_DungNgayHieuLuc_DaTraLuatMoi()
    {
        // Ranh giới: chính ngày ValidFrom đã thuộc luật mới, không phải hôm sau.
        SplitJune().For(new DateOnly(2026, 6, 15)).VersionId.Should().Be(2);
    }

    [Fact]
    public void For_NgayNgoaiBang_RoiVePeriodEnd_KhongNemLoi()
    {
        // Bản ghi lạc ngày không được làm vỡ cả bảng lương.
        SplitJune().For(new DateOnly(2026, 12, 31)).VersionId.Should().Be(2);
    }

    [Fact]
    public void Uniform_MoiNgayCungMotMuc_VaKhongBaoDoiLuat()
    {
        var timeline = LaborLawTimeline.Uniform(OldLaw);

        timeline.For(new DateOnly(2026, 6, 1)).VersionId.Should().Be(1);
        timeline.For(new DateOnly(2030, 1, 1)).VersionId.Should().Be(1);
        timeline.ChangedWithinPeriod.Should().BeFalse();
        timeline.Versions.Should().ContainSingle();
    }

    [Fact]
    public void Versions_GomTheoVersionId_XepTheoNgayHieuLuc()
    {
        var versions = SplitJune().Versions;

        versions.Should().HaveCount(2);
        versions[0].VersionId.Should().Be(1);
        versions[1].VersionId.Should().Be(2);
    }

    [Fact]
    public void ChangedWithinPeriod_CoHaiMuc_TraTrue()
    {
        SplitJune().ChangedWithinPeriod.Should().BeTrue();
    }

    // ===== Ghi chú =====

    [Fact]
    public void GhiChu_KhongDoiLuat_KhongSinhGhiChu()
    {
        MidPeriodComplianceNotes.ForLaborLaw(LaborLawTimeline.Uniform(OldLaw), DateTime.UtcNow)
            .Should().BeNull();
    }

    [Fact]
    public void GhiChu_DoiLuatGiuaKy_NeuRoMocVaCanCuPhapLy()
    {
        var note = MidPeriodComplianceNotes.ForLaborLaw(SplitJune(), new DateTime(2026, 7, 1));

        note.Should().NotBeNull();
        note!.NoteType.Should().Be(PayrollNoteType.LawChange);
        note.VersionType.Should().Be(ComplianceVersionType.LaborLawConstants);
        note.AutoGenerated.Should().BeTrue();
        note.Body.Should().Contain("15/06/2026").And.Contain("NĐ 99/2026 Đ.5");
        // Nói rõ ranh giới: cái gì chia theo ngày, cái gì vẫn là con số cả kỳ.
        note.Body.Should().Contain("TỪNG NGÀY CÔNG").And.Contain("Đơn giá giờ");
        note.LegalReference.Should().Be("NĐ 99/2026 Đ.5");
    }
}
