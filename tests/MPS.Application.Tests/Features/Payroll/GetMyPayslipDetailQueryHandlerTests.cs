using FluentAssertions;
using Moq;
using MPS.Application.Common.Interfaces;
using MPS.Application.Common.Payroll;
using MPS.Application.Features.Payroll.Common;
using MPS.Application.Features.Payroll.Queries;
using MPS.Domain.Constants;
using MPS.Domain.Entities.Payroll;
using MPS.Domain.Enums.Payroll;
using MPS.Domain.Exceptions;
using MPS.Domain.Interfaces;
using MPS.Domain.Interfaces.Payroll;
using EmployeeInformationEntity = MPS.Domain.Entities.EmployeeInformation;
using PositionEntity = MPS.Domain.Entities.Position;

namespace MPS.Application.Tests.Features.Payroll;

/// <summary>
/// GET /payroll/me/payslips/{periodId} — payload khớp 1-1 với PayrollSheetDto (rows: 1 phần tử).
/// - Header NV (name/position/bank last4) đúng
/// - Sheet có đủ columns/notes/complianceRefs, rows đúng 1, không có Total
/// - Gross/Net = effective value của TONGTHUNHAP/THUCNHAN
/// - Kỳ Draft, không tồn tại, NV không có dòng → 404 gộp
/// - Bank number có chữ/khoảng trắng → chỉ giữ 4 chữ số cuối
/// </summary>
public sealed class GetMyPayslipDetailQueryHandlerTests
{
    private const int UserId = 42;
    private const int EmployeeId = 7;
    private const int PeriodId = 20;

    private readonly Mock<IPayrollPeriodRepository> _periods = new();
    private readonly Mock<IContractLookupReader> _lookup = new();
    private readonly Mock<ICurrentUserService> _currentUser = new();

    private GetMyPayslipDetailQueryHandler CreateHandler()
    {
        _currentUser.SetupGet(c => c.UserId).Returns(UserId);
        _lookup.Setup(l => l.GetEmployeeInformationIdByUserIdAsync(UserId, It.IsAny<CancellationToken>()))
            .ReturnsAsync(EmployeeId);
        return new GetMyPayslipDetailQueryHandler(_periods.Object, _lookup.Object, _currentUser.Object);
    }

    private static PayrollPeriod BuildPeriod(
        PayrollPeriodStatus status,
        bool includeEmployeeRow = true,
        string? bankNumber = "1234567890123274")
    {
        var columns = new List<SalaryColumnDefinition>
        {
            new()
            {
                ColumnCode = PayrollColumnCodes.TongThuNhap, Label = "Tổng thu nhập",
                GroupName = "Thu nhập", DisplayOrder = 10,
                DataType = ColumnDataType.Money, ValueSource = ColumnValueSource.Formula,
                IsMoney = true, IsEditable = false,
            },
            new()
            {
                ColumnCode = PayrollColumnCodes.ThucNhan, Label = "Thực nhận",
                GroupName = "Thực nhận", DisplayOrder = 99,
                DataType = ColumnDataType.Money, ValueSource = ColumnValueSource.Formula,
                IsMoney = true, IsEditable = false,
            },
        };

        var period = new PayrollPeriod
        {
            Id = PeriodId,
            PeriodYear = 2026,
            PeriodMonth = 6,
            PayDate = new DateOnly(2026, 6, 30),
            StandardWorkingDays = 22m,
            Status = status,
            FormulaSnapshotJson = PayrollColumnSnapshotMapper.Serialize(columns),
        };

        period.ComplianceRefs.Add(new PayrollComplianceRef
        {
            VersionType = ComplianceVersionType.Pit,
            VersionId = 3, ValidFrom = new DateOnly(2026, 1, 1),
            LegalReference = "NĐ 65/2013/NĐ-CP",
            HeadlineLabel = "Biểu thuế TNCN",
        });
        period.Notes.Add(new PayrollNote
        {
            Id = 88, NoteType = PayrollNoteType.CapThreshold,
            ColumnCode = "ANTRUA", Title = "Trần cơm",
            Body = "Áp trần 730.000đ/tháng.", NewValue = 730000m,
            LegalReference = "TT 111/2013/TT-BTC", AutoGenerated = true,
        });

        if (includeEmployeeRow)
        {
            var row = new PayrollRow
            {
                Id = 501,
                EmployeeInformationId = EmployeeId,
                PayrollPeriodId = PeriodId,
                PayrollPeriod = period,
                RowType = PayrollRowType.Employee,
                EmployeeInformation = new EmployeeInformationEntity
                {
                    Id = EmployeeId,
                    FullName = "Nguyễn Thị Mai",
                    BankNumber = bankNumber,
                    Position = new PositionEntity { Id = 3, Name = "Senior Engineer" },
                },
            };
            row.Cells.Add(new PayrollCellValue { ColumnCode = PayrollColumnCodes.TongThuNhap, ComputedValue = 38_000_000m });
            row.Cells.Add(new PayrollCellValue
            {
                ColumnCode = PayrollColumnCodes.ThucNhan,
                ComputedValue = 30_000_000m,
                IsOverridden = true,
                OverrideValue = 31_000_000m,
            });
            period.Rows.Add(row);
        }

        return period;
    }

    [Fact]
    public async Task Returns_Sheet_And_Header_With_Effective_Values()
    {
        _periods.Setup(p => p.GetPeriodWithEmployeeRowAsync(PeriodId, EmployeeId, It.IsAny<CancellationToken>()))
            .ReturnsAsync(BuildPeriod(PayrollPeriodStatus.Locked));
        var handler = CreateHandler();

        var result = await handler.Handle(new GetMyPayslipDetailQuery(PeriodId), CancellationToken.None);

        result.Sheet.Id.Should().Be(PeriodId);
        result.Sheet.PeriodYear.Should().Be(2026);
        result.Sheet.PeriodMonth.Should().Be(6);
        result.Sheet.Status.Should().Be("Locked");
        result.Sheet.Columns.Should().HaveCount(2);
        result.Sheet.Rows.Should().HaveCount(1, "chỉ trả về dòng của chính NV, không có Total");
        result.Sheet.Rows[0].RowType.Should().Be("Employee");
        result.Sheet.Rows[0].EmployeeInformationId.Should().Be(EmployeeId);
        result.Sheet.Notes.Should().HaveCount(1);
        result.Sheet.ComplianceRefs.Should().HaveCount(1);

        result.Employee.EmployeeInformationId.Should().Be(EmployeeId);
        result.Employee.FullName.Should().Be("Nguyễn Thị Mai");
        result.Employee.PositionName.Should().Be("Senior Engineer");
        result.Employee.BankAccountLast4.Should().Be("3274");

        result.Gross.Should().Be(38_000_000m);
        result.Net.Should().Be(31_000_000m, "THUCNHAN override thắng computed");
    }

    [Fact]
    public async Task BankLast4_Ignores_NonDigits_And_Handles_Short_Number()
    {
        _periods.Setup(p => p.GetPeriodWithEmployeeRowAsync(PeriodId, EmployeeId, It.IsAny<CancellationToken>()))
            .ReturnsAsync(BuildPeriod(PayrollPeriodStatus.Locked, bankNumber: "VCB 007-32 74"));
        var handler = CreateHandler();

        var result = await handler.Handle(new GetMyPayslipDetailQuery(PeriodId), CancellationToken.None);

        result.Employee.BankAccountLast4.Should().Be("3274");
    }

    [Fact]
    public async Task BankLast4_Null_When_BankNumber_Missing()
    {
        _periods.Setup(p => p.GetPeriodWithEmployeeRowAsync(PeriodId, EmployeeId, It.IsAny<CancellationToken>()))
            .ReturnsAsync(BuildPeriod(PayrollPeriodStatus.Locked, bankNumber: null));
        var handler = CreateHandler();

        var result = await handler.Handle(new GetMyPayslipDetailQuery(PeriodId), CancellationToken.None);

        result.Employee.BankAccountLast4.Should().BeNull();
    }

    [Fact]
    public async Task Throws_NotFound_When_Period_Missing()
    {
        _periods.Setup(p => p.GetPeriodWithEmployeeRowAsync(PeriodId, EmployeeId, It.IsAny<CancellationToken>()))
            .ReturnsAsync((PayrollPeriod?)null);
        var handler = CreateHandler();

        var act = () => handler.Handle(new GetMyPayslipDetailQuery(PeriodId), CancellationToken.None);

        await act.Should().ThrowAsync<NotFoundException>();
    }

    [Fact]
    public async Task Throws_NotFound_When_Period_Is_Draft()
    {
        _periods.Setup(p => p.GetPeriodWithEmployeeRowAsync(PeriodId, EmployeeId, It.IsAny<CancellationToken>()))
            .ReturnsAsync(BuildPeriod(PayrollPeriodStatus.Draft));
        var handler = CreateHandler();

        var act = () => handler.Handle(new GetMyPayslipDetailQuery(PeriodId), CancellationToken.None);

        await act.Should().ThrowAsync<NotFoundException>();
    }

    [Fact]
    public async Task Throws_NotFound_When_Employee_Has_No_Row_In_Period()
    {
        _periods.Setup(p => p.GetPeriodWithEmployeeRowAsync(PeriodId, EmployeeId, It.IsAny<CancellationToken>()))
            .ReturnsAsync(BuildPeriod(PayrollPeriodStatus.Locked, includeEmployeeRow: false));
        var handler = CreateHandler();

        var act = () => handler.Handle(new GetMyPayslipDetailQuery(PeriodId), CancellationToken.None);

        await act.Should().ThrowAsync<NotFoundException>();
    }

    [Fact]
    public async Task Throws_NotFound_When_No_Employee_Profile()
    {
        _currentUser.SetupGet(c => c.UserId).Returns(UserId);
        _lookup.Setup(l => l.GetEmployeeInformationIdByUserIdAsync(UserId, It.IsAny<CancellationToken>()))
            .ReturnsAsync((int?)null);
        var handler = new GetMyPayslipDetailQueryHandler(_periods.Object, _lookup.Object, _currentUser.Object);

        var act = () => handler.Handle(new GetMyPayslipDetailQuery(PeriodId), CancellationToken.None);

        await act.Should().ThrowAsync<NotFoundException>();
    }
}
